// PROTOTYPE tool: regenerates model.js from a .vrm file so the stage can load
// the model over file:// (fetch/XHR to local files are blocked; a classic
// <script> payload is not). Throwaway; not part of src/.
// Run: node prototype/vrm/pack-model.cjs [path-to.vrm]
const fs = require('fs')
const path = require('path')

const src = path.resolve(process.argv[2] || path.join(__dirname, '..', '1754622352515258289.vrm'))
const out = path.join(__dirname, 'model.js')
const buf = fs.readFileSync(src)
const magic = buf.readUInt32LE(0)
if (magic !== 0x46546c67) {
  console.error('not a GLB/VRM (bad magic):', src)
  process.exit(1)
}
fs.writeFileSync(
  out,
  '// GENERATED by pack-model.cjs from ' + path.basename(src) + ' — do not edit.\n' +
    'window.MITA_VRM_B64="' + buf.toString('base64') + '";\n' +
    'window.MITA_VRM_NAME=' + JSON.stringify(path.basename(src)) + ';\n',
)
console.log('wrote', out, (buf.length / 1024 / 1024).toFixed(1) + 'MB from', path.basename(src))
