// PROTOTYPE tool: regenerates anim-idle.js from a Mixamo .fbx clip so the stage
// can load the idle animation over file:// (fetch/XHR to local files are
// blocked; a classic <script> payload is not). Throwaway; not part of src/.
// Source clip: Mixamo "Idle" retarget clip, mirrored from the ai-smash project
// (https://muxai.vercel.app/mixamo_idle.fbx). Mixamo clips are royalty-free.
// Run: node prototype/vrm/pack-anim.cjs [path-to.fbx]
const fs = require('fs')
const path = require('path')

const src = path.resolve(process.argv[2] || path.join(__dirname, 'anims', 'mixamo_idle.fbx'))
const out = path.join(__dirname, 'anim-idle.js')
const buf = fs.readFileSync(src)
// FBX binary magic: "Kaydara FBX Binary  \x00"
if (buf.readUInt32LE(0) !== 0x614b2020 && buf.toString('ascii', 0, 20).indexOf('Kaydara FBX') !== 0) {
  console.error('not an FBX (bad magic):', src)
  process.exit(1)
}
fs.writeFileSync(
  out,
  '// GENERATED by pack-anim.cjs from ' + path.basename(src) + ' — do not edit.\n' +
    'window.MITA_ANIM_IDLE_B64="' + buf.toString('base64') + '";\n' +
    'window.MITA_ANIM_IDLE_NAME=' + JSON.stringify(path.basename(src)) + ';\n',
)
console.log('wrote', out, (buf.length / 1024 / 1024).toFixed(1) + 'MB from', path.basename(src))
