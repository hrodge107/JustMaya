// Isolated prototype interactions; no backend, provider or stored learner data.
const { chromium } = require('playwright-core')
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
const os = require('node:os')
const base = 'http://127.0.0.1:5195/src/player/picture-note-prototype.html'
const output = path.join(os.tmpdir(), 'mita-picture-prototype')
fs.mkdirSync(output, { recursive: true })

;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
  const evidence = []
  try {
    for (const width of [320, 390, 768, 1280]) {
      const context = await browser.newContext({ viewport: { width, height: 844 }, reducedMotion: width === 1280 ? 'no-preference' : 'reduce', hasTouch: width < 500 })
      const page = await context.newPage()
      const errors = []
      page.on('pageerror', e => errors.push(e.message))
      page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
      await page.goto(base)
      const gallery = page.getByRole('button', { name: 'Gallery', exact: true })
      const menu = page.getByRole('button', { name: 'Menu', exact: true })
      const g = await gallery.boundingBox(), m = await menu.boundingBox()
      assert(g.x + g.width <= m.x && Math.abs(g.y - m.y) < 2)
      await gallery.click()
      await page.getByText('No picture notes yet.', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'Return to lesson' }).click()
      assert(await gallery.evaluate(el => el === document.activeElement))
      await page.getByRole('button', { name: 'Next scene' }).click()
      await page.locator('.pn-scene-card img:not([hidden])').waitFor()
      await page.screenshot({ path: path.join(output, `scene-${width}.png`), fullPage: true })
      await page.locator('.pn-scene-card .pn-front').focus()
      await page.keyboard.press('Enter')
      await page.getByRole('heading', { name: 'PDF citations' }).waitFor()
      assert.equal(await page.locator('dialog a').first().getAttribute('href'), '/sample-chapter.pdf#page=2')
      assert.equal((await page.request.get('http://127.0.0.1:5195/sample-chapter.pdf')).status(), 200)
      await page.keyboard.press('Escape')
      assert(await page.locator('.pn-scene-card .pn-front').evaluate(el => el === document.activeElement))
      await page.getByRole('button', { name: 'Dismiss Why rivers mattered' }).click()
      assert.equal(await page.locator('.pn-scene-card').count(), 0)
      await page.getByRole('button', { name: 'Next scene' }).click()
      await page.getByRole('button', { name: 'Previous scene' }).click()
      assert.equal(await page.locator('.pn-scene-card').count(), 0)
      await gallery.click()
      assert.equal(await page.locator('.pn-grid .pn-front').count(), 2)
      await page.screenshot({ path: path.join(output, `gallery-${width}.png`) })
      await page.locator('dialog').evaluate(el => { el.scrollTop = 100 })
      const scrollBefore = await page.locator('dialog').evaluate(el => el.scrollTop)
      await page.getByRole('button', { name: 'Open Why rivers mattered' }).click()
      await page.getByRole('button', { name: 'Back to Gallery' }).click()
      assert(await page.locator('[data-note="0"]').evaluate(el => el === document.activeElement))
      assert.equal(await page.locator('dialog').evaluate(el => el.scrollTop), scrollBefore)
      await page.getByRole('button', { name: 'Open From surplus to specialists' }).click()
      await page.screenshot({ path: path.join(output, `detail-${width}.png`) })
      await page.getByRole('button', { name: 'Close', exact: true }).click()
      await menu.click()
      await page.keyboard.press('Shift+Tab')
      assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Reset demo')
      await page.keyboard.press('Tab')
      assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Close')
      await page.getByRole('button', { name: 'Reset demo' }).click()
      await gallery.click()
      await page.getByText('No picture notes yet.', { exact: true }).waitFor()
      await page.keyboard.press('Escape')
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
      assert.equal(overflow, false)
      assert.deepEqual(errors, [])
      evidence.push(`${width}px: rail placement; empty Gallery; scene modal/citation; Escape/focus; dismissal/revisit; two notes/no duplicates; Gallery detail/Back/focus; Close; Menu/reset; keyboard trap; no overflow or console errors.`)
      await context.close()
    }
    for (const query of ['?images=broken', '?images=loading', '?long']) {
      const page = await browser.newPage({ viewport: { width: 390, height: 700 } })
      await page.goto(base + query)
      await page.getByRole('button', { name: 'Next scene' }).click()
      if (query.includes('broken')) await page.getByText('Image unavailable', { exact: true }).waitFor()
      if (query.includes('loading')) await page.getByText('Loading image…', { exact: true }).waitFor()
      await page.locator('.pn-scene-card .pn-front').click()
      await page.getByRole('heading', { name: 'PDF citations' }).waitFor()
      assert.equal(await page.locator('dialog').evaluate(el => el.scrollWidth > el.clientWidth), false)
      await page.getByRole('button', { name: 'Close', exact: true }).click()
      evidence.push(`${query}: note remains usable; detail/citations available; no modal horizontal overflow; Close reachable.`)
      await page.close()
    }
    fs.writeFileSync(path.join(output, 'evidence.json'), JSON.stringify(evidence, null, 2))
    console.log(evidence.join('\n'))
    console.log(`Screenshots: ${output}`)
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
