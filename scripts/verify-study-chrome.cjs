// Browser-level coverage for the shared background choice and responsive chrome.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')

async function run() {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' })
  await context.addInitScript(() => localStorage.setItem('meet-mita:motion', 'reduce'))
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const session = { sessionId: 's', episodeId: 'e', mode: 'playing', sceneId: 'a', dialogueIndex: 0, version: 1, status: 'active' }
  const episode = { episodeId: 'e', title: 'A lesson', startSceneId: 'a', scenes: [{ sceneId: 'a', kind: 'dialogue', nextSceneId: null, question: null, dialogue: [{ lineId: 'one', speaker: 'mascot', text: 'Hello.', emotion: 'idle' }] }] }
  await page.route('**/api/**', route => route.fulfill({ json: route.request().url().includes('/sessions/') ? session : episode }))
  await page.goto('http://127.0.0.1:5173/')
  const button = page.locator('.study-background')
  await button.waitFor()
  async function checkBackgroundPosition() {
    const header = await page.locator('.study-header').boundingBox()
    const control = await button.boundingBox()
    assert.ok(control.y >= header.y + header.height, 'background control sits below header')
    assert.ok(control.x < 32, 'background control sits at the left edge')
  }
  await checkBackgroundPosition()
  const railColors = await page.locator('.rail .vn-menu-trigger').first().evaluate(el => ({ bg: getComputedStyle(el).backgroundColor, fg: getComputedStyle(el).color, ring: getComputedStyle(el).boxShadow }))
  assert.equal(railColors.bg, 'rgb(52, 64, 94)')
  assert.equal(railColors.fg, 'rgb(255, 255, 255)')
  assert.notEqual(railColors.ring, 'none')
  await page.screenshot({ path: require('node:path').join(require('node:os').tmpdir(), 'mita-study-home.png') })
  assert.equal(await page.locator('.home').getAttribute('data-background'), 'bedroom')
  await button.click()
  assert.equal(await page.locator('.home').getAttribute('data-background'), 'study')
  await page.goto('http://127.0.0.1:5173/?session=s')
  await page.locator('.vn-frame').waitFor()
  await checkBackgroundPosition()
  assert.equal(await page.locator('.study-brand').isVisible(), true)
  assert.equal(await page.locator('.study-brand').evaluate(el => el.contains(document.elementFromPoint(el.getBoundingClientRect().x + 15, el.getBoundingClientRect().y + 15))), true, 'brand is not obscured')
  await page.screenshot({ path: require('node:path').join(require('node:os').tmpdir(), 'mita-study-player.png') })
  assert.equal(await page.locator('.player').getAttribute('data-background'), 'study')
  await button.click()
  assert.equal(await page.locator('.player').getAttribute('data-background'), 'none')
  await page.reload()
  await page.locator('.vn-frame').waitFor()
  assert.equal(await page.locator('.player').getAttribute('data-background'), 'none')
  await button.click()
  assert.equal(await page.locator('.player').getAttribute('data-background'), 'bedroom')
  for (const size of [{ width: 390, height: 844 }, { width: 768, height: 1024 }, { width: 1280, height: 900 }]) {
    await page.setViewportSize(size)
    await checkBackgroundPosition()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `overflow at ${size.width}`)
    await button.click({ trial: true })
    await page.locator('.vn-menu-trigger').last().click({ trial: true })
  }
  await page.goto('http://127.0.0.1:5173/')
  await page.setViewportSize({ width: 390, height: 844 })
  await checkBackgroundPosition()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Home fits mobile')
  const dialogue = await page.locator('.dlg').boundingBox()
  const homeRail = await page.locator('.rail').boundingBox()
  assert.ok(dialogue.y + dialogue.height <= homeRail.y + 1, 'Home mobile rail remains below dialogue')
  await button.focus()
  await page.keyboard.press('Enter')
  assert.equal(await page.locator('.home').getAttribute('data-background'), 'study')
  const blocked = await browser.newContext({ reducedMotion: 'reduce' })
  await blocked.addInitScript(() => Object.defineProperty(window, 'localStorage', { get() { throw new Error('blocked') } }))
  const fallback = await blocked.newPage()
  await fallback.route('**/backgrounds/**', route => route.abort())
  await fallback.goto('http://127.0.0.1:5173/')
  await fallback.locator('.study-background').click()
  assert.equal(await fallback.locator('.home').getAttribute('data-background'), 'study')
  assert.equal(await fallback.locator('.b-scene').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(35, 35, 58)')
  await blocked.close()
  assert.deepEqual(errors, [])
  console.log('Shared background cycle, persistence, player handoff, responsive controls: PASS')
  await browser.close()
}
run().catch(error => { console.error(error); process.exitCode = 1 })
